import math


def area(r):
    '''
    Принимает радиус круга r, возвращает площадь этого круга.

    Например, area(3) вернет 28.274...
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Принимает радиус окружности, возвращает длину окружности

    Например, perimeter(3) вернет 18.849...
    '''
    return 2 * math.pi * r