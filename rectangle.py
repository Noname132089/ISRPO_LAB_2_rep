def area(a, b):
    '''
    Возвращает площадь прямоугольника со сторонами a и b.

        Параметры:
            a: длина прямоугольника
            b: ширина прямоугольника
    '''
    return a * b 

def perimeter(a, b):
    '''
    Возвращает периметр прямоугольника со сторонами a и b.

        Параметры:
            a: длина прямоугольника
            b: ширина прямоугольника
    '''
    return (a + b) * 2