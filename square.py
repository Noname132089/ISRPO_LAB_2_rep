def area(a):
    '''
    Возвращает площадь квадрата со стороной a.

        Параметры:
            a: длина стороны квадрата
    '''
    return a * a


def perimeter(a):
    '''
    Возвращает периметр квадрата со стороной a.

        Параметры:
            a: длина стороны квадрата
    '''
    return 4 * a
