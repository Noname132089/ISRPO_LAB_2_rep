def area(a):
    '''
    Возвращает площадь квадрата со стороной a.

        Параметры:
            a: длина стороны квадрата
    Например, при area(5) вернет 25
    '''
    return a * a


def perimeter(a):
    '''
    Возвращает периметр квадрата со стороной a.

        Параметры:
            a: длина стороны квадрата
    Например, при perimeter(5) вернет 20
    '''
    return 4 * a
