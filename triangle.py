def area(a, h): 
    '''
    Возвращает площадь треугольника со стороной a и опущенной на неё высотой h.

        Параметры:
            a: длина стороны (основания) треугольника
            h: высота треугольника, опущенная на сторону a

        Возвращаемое значение:
            площадь треугольника (a * h / 2)

    Например, при area(3, 4) вернёт 6.0
    '''
    return a * h / 2 


def perimeter(a, b, c): 
    '''
    Возвращает периметр треугольника со сторонами a, b, c.

        Параметры:
            a: первая сторона треугольника
            b: вторая сторона треугольника
            c: третья сторона треугольника

        Возвращаемое значение:
            периметр треугольника (a + b + c)

    Например, при perimeter(3, 4, 5) вернёт 12
    '''
    return a + b + c