def area(a, h): 
    '''
    Возвращает площадь треугольника со стороной a и высотой h, которая идет от вершины, не принадлежащей стороне a
    
        Параметры:
            a - сторона a
            h - высота треугольника, которая идет от вершины, не принадлежащей стороне a
    '''
    return a * h / 2 

def perimeter(a, b, c): 
    '''
    Возвращает периметр треугольника со сторонами a, b, c

        Параметры:
            a - первая сторона треугольника
            b - вторая сторона треугольника
            c - третья сторона треугольника
    '''
    return a + b + c 
